    Exceptions are unexpected events/errors that can occur
    during the execution of a program.

    1. Exception handling in Scala is similar to Java,
       but Scala provides some additional approaches.

    2. In Java, exceptions are broadly categorized as:
       a) Checked Exceptions
          - Checked at compile time.
          - Must be handled or declared using throws.
          - Example: IOException

       b) Unchecked Exceptions
          - Occur at runtime.
          - Handling is optional.
          - Example: NullPointerException, ArithmeticException

    3. Scala does NOT have checked exceptions.
       All exceptions are unchecked.
       Therefore, we are not forced to catch or declare
       an exception at compile time.

    4. There are two broad ways to deal with exceptions:

       a) Throw the exception
          - Use throw keyword when we want to explicitly
            generate an exception.

       b) Handle the exception
          i)  try-catch-finally
          ii) Try with Success / Failure
          iii) Catch object
   */

